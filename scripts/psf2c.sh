#!/usr/bin/env bash
# SPDX-License-Identifier: MIT
# psf2c.sh: a PSF1 or PSF2 console font (.psf or .psf.gz) -> a C header with the 8x16 glyphs of
# printable ASCII (0x20..0x7e) for src/mi/osd.c: osd_font[95][16], one byte per row, the leftmost
# pixel in the high bit, and OSD_FONT_NAME. Each character's glyph is looked up in the font's
# Unicode table (console fonts aren't in ASCII order); a font without a table must be. Fails on
# anything else: not PSF, not 8x16, truncated, or a printable ASCII character without a glyph.
# Only gzip, od and a POSIX awk are needed (all in Ubuntu's base image). src/build.sh runs it:
#
#   scripts/psf2c.sh FONT.psf.gz "NAME" > build/gen/osd_font.h
set -euo pipefail
[ $# -eq 2 ] || { echo "usage: $0 FONT.psf[.gz] NAME" >&2; exit 2; }
font=$1
name=$2
[[ "$name" =~ ^[A-Za-z0-9\ ._,:()+/~-]{1,100}$ ]] || { echo "psf2c: NAME: letters, digits, spaces, ._,:()+/~- only" >&2; exit 2; }
case "$font" in
*.gz) gzip -dc -- "$font" ;;
*) cat -- "$font" ;;
esac | od -An -v -tu1 | awk -v name="$name" -v src="${font##*/}" '
{ for (i = 1; i <= NF; i++) b[n++] = $i + 0 }
function u32(o) { return b[o] + 256 * (b[o + 1] + 256 * (b[o + 2] + 256 * b[o + 3])) }
function die(m) { print "psf2c: " src ": " m > "/dev/stderr"; failed = 1; exit 1 }
END {
	if (failed) exit 1
	if (n >= 4 && b[0] == 54 && b[1] == 4) {                        # PSF1: 36 04 mode charsize
		mode = b[2]; h = b[3]; w = 8; cs = h; hdr = 4
		cnt = mode % 2 ? 512 : 256                              # PSF1_MODE512
		tab = int(mode / 2) % 4 != 0                            # PSF1_MODEHASTAB | MODEHASSEQ
		o = hdr + cnt * cs
		for (g = 0; tab && g < cnt && o + 1 < n;) {             # u16 LE per glyph, FFFF ends it
			v = b[o] + 256 * b[o + 1]; o += 2
			if (v == 65535) { g++; seq = 0 }
			else if (v == 65534) seq = 1                    # FFFE: combining sequences follow
			else if (!seq && v >= 32 && v <= 126 && !(v in glyph)) glyph[v] = g
		}
	} else if (n >= 32 && b[0] == 114 && b[1] == 181 && b[2] == 74 && b[3] == 134) {  # PSF2
		hdr = u32(8); flags = u32(12); cnt = u32(16); cs = u32(20); h = u32(24); w = u32(28)
		tab = flags % 2                                         # PSF2_HAS_UNICODE_TABLE
		o = hdr + cnt * cs
		for (g = 0; tab && g < cnt && o < n;) {                 # UTF-8 per glyph, FF ends it
			c = b[o]
			if (c == 255) { g++; seq = 0; o++ }
			else if (c == 254) { seq = 1; o++ }             # FE: sequences follow
			else if (c < 128) { if (!seq && c >= 32 && c <= 126 && !(c in glyph)) glyph[c] = g; o++ }
			else o += c >= 240 ? 4 : c >= 224 ? 3 : c >= 192 ? 2 : 1
		}
	} else die("not a PSF1 or PSF2 font")
	if (w != 8 || h != 16 || cs != 16) die("glyphs are " w "x" h " (" cs " bytes), not 8x16")
	if (hdr + cnt * cs > n) die("truncated: " n " bytes")
	printf "/* Generated by scripts/psf2c.sh from %s; do not edit. %s: the 8x16 glyphs of\n", src, name
	printf " * printable ASCII, a byte per row, the leftmost pixel in the high bit. */\n"
	printf "#define OSD_FONT_NAME \"%s\"\n", name
	printf "static const uint8_t osd_font[95][16] = {\n"
	for (c = 32; c <= 126; c++) {
		if (tab && !(c in glyph)) die(sprintf("no glyph for 0x%02x", c))
		g = tab ? glyph[c] : c
		if (g >= cnt) die(sprintf("glyph %d for 0x%02x out of range", g, c))
		line = "\t{"
		for (r = 0; r < 16; r++) line = line sprintf(" 0x%02x%s", b[hdr + g * cs + r], r < 15 ? "," : "")
		printf "%s },\t/* 0x%02x */\n", line, c
	}
	printf "};\n"
}'
