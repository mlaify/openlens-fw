"""Generate tools/iq-dump/iq_groups.h (IQ API group id, byte size, name) from the camera's
/config/iqfile/isp_api.xml (a vendor file: read it locally, never commit it).

  python3 -I scripts/gen-iq-groups.py <path/to/isp_api.xml> > tools/iq-dump/iq_groups.h

Size = sum of the items' Type x M x N; the XML spells out padding items, so this matches the
kernel's struct for the groups we checked (iq-dump logs any group the kernel rejects).
"""
import sys
import xml.etree.ElementTree as ET

SIZE = {"U8": 1, "S8": 1, "U16": 2, "S16": 2, "U32": 4, "S32": 4}
root = ET.parse(sys.argv[1]).getroot()
print("/* generated by scripts/gen-iq-groups.py from isp_api.xml (" + root.get("Name", "") + ") */")
print("static const struct { uint32_t id, size; const char *name; } iq_groups[] = {")
seen = set()
for page in root.iter("PAGE"):
    for g in page.iter("GROUP"):
        gid = int(g.get("Id"))
        if gid in seen:
            continue
        seen.add(gid)
        size = sum(SIZE[i.get("Type")] * int(i.get("M", "1")) * int(i.get("N", "1"))
                   for i in g.iter("ITEM"))
        print(f'\t{{ {gid}, {size}, "{page.get("Name")}/{g.get("Name")}" }},')
print("};")
